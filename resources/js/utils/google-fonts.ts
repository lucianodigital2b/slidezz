/**
 * Fonts bundled locally via @font-face (see resources/css/app.css) instead of the
 * Google catalog. They must NOT get a Google stylesheet link — the faces are
 * already declared — but still appear in the picker and load like any other font.
 */
export const CUSTOM_FONTS: string[] = ['Euclid Circular A'];

/** The full font picker catalog: locally-bundled fonts first, then the Google catalog. */
export const EDITOR_FONTS: string[] = [...CUSTOM_FONTS, ...GOOGLE_FONTS];

// Cache the in-flight load PROMISE per family (not just a "started" flag).
// Concurrent callers must await the same real load — marking a font "loaded"
// before the await completes would let later callers resolve immediately while
// the font is still loading, so they'd measure/lay out text with fallback-font
// metrics and bake in wrong positions (e.g. extra gaps around words) that never
// self-correct. Returning the shared promise fixes that for every caller.
const loadPromises = new Map<string, Promise<void>>();

export function loadGoogleFont(family: string): Promise<void> {
    const existing = loadPromises.get(family);
    if (existing) return existing;

    const promise = (async () => {
        const key = family.replace(/ /g, '+');
        const id = `gf-${key}`;

        // Locally-bundled faces (@font-face in app.css) have no Google stylesheet;
        // skip the link and just wait for the already-declared faces to be ready.
        if (!CUSTOM_FONTS.includes(family) && !document.getElementById(id)) {
            const link = document.createElement('link');
            link.id = id;
            link.rel = 'stylesheet';
            // Serve the full 300-900 weight range (upright + italic) so the weight
            // picker and templates can use any weight, not just 400/700. css2 is lenient
            // with a discrete list — single-weight faces (e.g. Anton) still return 200 and
            // just serve what they have; a variable font serves the whole range in one file.
            // (A `300..900` RANGE, by contrast, 400s for static fonts, so we list them.)
            link.href = `https://fonts.googleapis.com/css2?family=${key}:ital,wght@0,300;0,400;0,500;0,600;0,700;0,800;0,900;1,300;1,400;1,500;1,600;1,700;1,800;1,900&display=swap`;

            // Wait for the stylesheet to be parsed so FontFace objects are registered
            // before calling document.fonts.load() — otherwise it resolves immediately
            // with an empty array and the font won't be ready for canvas rendering.
            await new Promise<void>((resolve) => {
                link.addEventListener('load', resolve, { once: true });
                link.addEventListener('error', resolve, { once: true });
                document.head.appendChild(link);
            });
        }

        try {
            await Promise.all(
                ['300', '400', '500', '600', '700', '800', '900'].map((w) =>
                    document.fonts.load(`${w} 16px "${family}"`),
                ),
            );
        } catch {
            // silently fall back if the font fails
        }
    })();

    loadPromises.set(family, promise);
    return promise;
}
